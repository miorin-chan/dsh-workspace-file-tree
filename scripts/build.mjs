/**
 * Build this plugin's Host and Client halves from TypeScript sources.
 *
 *   src/host/index.ts        → index.js    ESM for the Host process
 *   src/client/index.ts(x)   → client.js   classic script for the Web module loader
 *   src/lib/*.ts             → lib/*.js    private Host modules, when src/lib/ exists
 *
 * DSH serves one classic script per plugin; its module loader runs the wrapper
 * factory lazily and provides `react` and the seeded platform modules from the
 * shell's frozen table. Everything else is inlined, so the Client artifact is
 * self-contained apart from those externals.
 *
 * Usage:
 *   node scripts/build.mjs           write both artifacts
 *   node scripts/build.mjs --check   fail when an artifact is stale
 *
 * The `prepare` script builds the local artifacts during dependency installation
 * and packaging. Use `--check` to compare existing artifacts with the sources.
 */

import { createRequire } from 'node:module'
import { existsSync } from 'node:fs'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const { build } = require('esbuild')

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const pkg = JSON.parse(await readFile(resolve(ROOT, 'package.json'), 'utf8'))

/** Packages the Web shell seeds into its module table; every other import is bundled. */
const CLIENT_EXTERNAL = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/*',
]

const HOST_EXTERNAL = ['node:*']

/** Rewrite `../lib/<name>.js` from `src/host` to `./lib/<name>.js` in the generated `index.js`. */
const HOST_MODULE_IMPORT = /^\.\.\/lib\/(.+\.js)$/

/** Keep the Host entry's private-module imports on the generated `lib/` artifacts. */
const hostModules = {
  name: 'host-modules',
  setup(context) {
    context.onResolve({ filter: HOST_MODULE_IMPORT }, (args) => ({
      path: './lib/' + HOST_MODULE_IMPORT.exec(args.path)[1],
      external: true,
    }))
  },
}

/** Wrap an esbuild CommonJS bundle in DSH's module-loader envelope. */
function envelope(code) {
  return `/**
 * ${pkg.name} browser half. Generated by scripts/build.mjs from src/client/;
 * do not edit by hand. React and the seeded platform modules come from the
 * host module table.
 */
window.__ModuleLoader__.load({
  id: '${pkg.name}',
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  },
});
`
}

/** The first existing entry among `candidates`, resolved from the package root. */
function entryOf(candidates) {
  return candidates.map((name) => resolve(ROOT, name)).find((path) => existsSync(path))
}

/** Every `.ts` source under `dir`, as `/`-joined paths relative to it, sorted. */
async function sourcesOf(dir) {
  const found = []
  async function walk(prefix) {
    const entries = await readdir(resolve(dir, prefix), { withFileTypes: true })
    for (const entry of entries) {
      const path = prefix === '' ? entry.name : `${prefix}/${entry.name}`
      if (entry.isDirectory()) {
        await walk(path)
      } else if (entry.name.endsWith('.ts') && !entry.name.endsWith('.d.ts')) {
        found.push(path)
      }
    }
  }
  await walk('')
  return found.sort()
}

/**
 * Compile one module on its own, leaving every import specifier untouched.
 * Private modules keep their `./sibling.js` imports because the emitted tree
 * mirrors the source tree and the artifacts run from `lib/`.
 */
async function compileModule(entry, options, banner) {
  const result = await build({
    entryPoints: [entry],
    bundle: false,
    write: false,
    banner: { js: banner },
    legalComments: 'none',
    logLevel: 'warning',
    ...options,
  })
  return result.outputFiles[0].text
}

async function compile(entry, options, banner) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    banner: { js: banner },
    jsx: 'automatic',
    minify: false,
    legalComments: 'none',
    logLevel: 'warning',
    ...options,
  })
  return result.outputFiles[0].text
}

const targets = []

const hostEntry = entryOf(['src/host/index.ts', 'src/host/index.tsx'])
if (hostEntry !== undefined) {
  const banner = `/** ${pkg.name} host half. Generated by scripts/build.mjs from src/host/; do not edit by hand. */`
  const code = await compile(hostEntry, {
    format: 'esm',
    platform: 'node',
    external: HOST_EXTERNAL,
    plugins: [hostModules],
  }, banner)
  targets.push({ file: 'index.js', content: code })
}

const clientEntry = entryOf(['src/client/index.tsx', 'src/client/index.ts'])
if (clientEntry !== undefined) {
  const code = await compile(clientEntry, { format: 'cjs', platform: 'browser', target: 'es2020', external: CLIENT_EXTERNAL }, '')
  targets.push({ file: 'client.js', content: envelope(code) })
}

// Private Host modules stay separate artifacts: tests and the published package
// import `lib/<name>.js` directly, so the Host bundle must not inline them away.
// The `hostModules` plugin above points the Host entry's `../lib/<name>.js`
// imports to the generated modules.
const moduleDir = resolve(ROOT, 'src/lib')
if (existsSync(moduleDir)) {
  for (const path of await sourcesOf(moduleDir)) {
    const banner = `/** ${pkg.name} host runtime module. Generated by scripts/build.mjs from src/lib/; do not edit by hand. */`
    const code = await compileModule(resolve(moduleDir, path), { format: 'esm', platform: 'node', target: 'es2022' }, banner)
    targets.push({ file: `lib/${path.replace(/\.ts$/, '.js')}`, content: code })
  }
}

if (targets.length === 0) {
  console.error('no Host or Client entry under src/; nothing to build')
  process.exitCode = 1
}

let stale = false
for (const { file, content } of targets ?? []) {
  const output = resolve(ROOT, file)
  if (CHECK) {
    const current = existsSync(output) ? await readFile(output, 'utf8') : ''
    if (current !== content) {
      console.error(`${file} is stale; run \`node scripts/build.mjs\`.`)
      stale = true
    } else {
      console.log(`${file} is up to date.`)
    }
  } else {
    await mkdir(dirname(output), { recursive: true })
    await writeFile(output, content)
    console.log(`wrote ${file} (${(content.length / 1024).toFixed(1)} KiB)`)
  }
}
if (stale) process.exitCode = 1
